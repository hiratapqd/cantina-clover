import { chromium } from '@playwright/test';
import assert from 'node:assert/strict';
import { mkdir, mkdtemp, rm } from 'node:fs/promises';
import path from 'node:path';
import { tmpdir } from 'node:os';
import { createServer } from '../server.js';
const dir=await mkdtemp(path.join(tmpdir(),'casinha-browser-test-'));
const server=createServer({file:path.join(dir,'central.json')});
await new Promise(resolve=>server.listen(0,'127.0.0.1',resolve));
const origin=`http://127.0.0.1:${server.address().port}`;
let browser;
try {
  browser=await chromium.launch({channel:'msedge',headless:true});
  const context=await browser.newContext({viewport:{width:1440,height:1080}});
  const page=await context.newPage();const errors=[];
  page.on('pageerror',error=>errors.push(error.message));
  await page.goto(origin);
  await page.getByRole('heading',{name:'Vamos atender?'}).waitFor();
  await page.evaluate(async()=>{await navigator.serviceWorker.ready;if(!navigator.serviceWorker.controller)await new Promise(resolve=>navigator.serviceWorker.addEventListener('controllerchange',resolve,{once:true}));});
  await mkdir('.work',{recursive:true});await page.screenshot({path:'.work/home-desktop.png',fullPage:true});
  await page.getByRole('button',{name:'Nova comanda',exact:true}).click();
  await page.getByRole('button',{name:'Abrir comanda',exact:false}).click();
  assert.match(await page.locator('#order-header').innerText(),/0001/);
  assert.match(await page.locator('#order-header').innerText(),/Somente número/);
  await page.getByRole('button',{name:'Livros',exact:true}).click();
  await page.getByRole('button',{name:'Livros novos',exact:true}).click();
  const firstIsbn=(await page.locator('.product-row small').first().innerText()).match(/\d{13}/)[0];
  await page.locator('.product-row').first().click();
  await page.getByRole('button',{name:'Adicionar e continuar'}).click();
  await page.getByRole('button',{name:'Livros',exact:true}).click();
  await page.getByRole('button',{name:'Livros usados',exact:false}).click();
  await page.getByRole('searchbox').fill(firstIsbn);
  await page.locator('.product-row').first().click();
  await page.getByRole('button',{name:'Adicionar e conferir'}).click();
  await page.getByRole('heading',{name:'Confira a comanda'}).waitFor();
  assert.equal(await page.locator('.review-row').count(),2);
  await page.screenshot({path:'.work/review-desktop.png',fullPage:true});
  await page.getByRole('button',{name:'Corrigir',exact:true}).first().click();
  await page.getByRole('spinbutton').fill('0');
  await page.getByRole('button',{name:'Salvar correção'}).click();
  await page.getByRole('heading',{name:'Confira a comanda'}).waitFor();
  assert.equal(await page.locator('.review-row').count(),1);
  assert.match(await page.locator('#order-total').innerText(),/10,00/);
  await page.getByRole('button',{name:'Receber pagamento',exact:true}).click();
  await page.getByRole('button',{name:'Pix',exact:true}).click();
  await page.getByRole('heading',{name:'Confirmar recebimento?'}).waitFor();
  assert.match(await page.locator('#order-header').innerText(),/Aberta/);
  await page.getByRole('button',{name:'Confirmar pagamento simulado',exact:true}).click();
  await page.getByRole('heading',{name:'Comanda finalizada!'}).waitFor();
  await page.getByRole('button',{name:'Novo atendimento'}).click();
  await context.setOffline(true);await page.reload();
  await page.getByRole('heading',{name:'Vamos atender?'}).waitFor();
  await page.getByRole('button',{name:'Nova comanda',exact:true}).click();
  await page.getByRole('textbox',{name:'Nome (opcional)'}).fill('Voluntária Offline');
  await page.getByRole('button',{name:'Abrir comanda',exact:false}).click();
  await page.getByRole('button',{name:'Bebidas',exact:true}).click();
  await page.locator('.product-row').first().click();
  await page.getByRole('button',{name:'Adicionar e conferir'}).click();
  await page.getByRole('heading',{name:'Confira a comanda'}).waitFor();
  const offlineTotal=await page.locator('#order-total').innerText();
  await page.reload();await page.getByRole('heading',{name:'Confira a comanda'}).waitFor();
  assert.equal(await page.locator('#order-total').innerText(),offlineTotal);
  await context.setOffline(false);await page.getByRole('button',{name:'Sincronizar demonstração'}).click();
  await page.waitForFunction(()=>document.querySelector('#sync-info').textContent.includes('Último envio'));
  await page.locator('#home-button').click();
  await page.getByRole('button',{name:'Comandas abertas',exact:true}).click();
  await page.getByRole('searchbox').fill('Voluntária Offline');
  await page.locator('.product-row').first().click();
  await page.setViewportSize({width:390,height:844});
  await page.getByRole('button',{name:'Aumentar letras'}).click();
  await page.screenshot({path:'.work/mobile-large-font.png',fullPage:true});
  assert.equal(await page.evaluate(()=>document.documentElement.scrollWidth>innerWidth),false);
  await page.locator('#home-button').click();
  await page.getByRole('button',{name:'Nova comanda',exact:true}).click();
  await page.getByRole('button',{name:'Abrir comanda',exact:false}).click();
  await page.getByRole('button',{name:'Água para fluidificar',exact:true}).click();
  await page.getByRole('heading',{name:'Agua grande 1,5l',exact:true}).waitFor();
  assert.equal(await page.getByRole('spinbutton').inputValue(),'1');
  await page.getByRole('spinbutton').fill('2');
  await page.getByRole('button',{name:'Fechar comanda',exact:true}).click();
  await page.getByRole('heading',{name:'Confira a comanda'}).waitFor();
  assert.equal(await page.locator('.review-row').count(),1);
  assert.match(await page.locator('.review-row').innerText(),/2 ×/);
  assert.match(await page.locator('#order-total').innerText(),/12,00/);
  assert.match(await page.locator('#order-header').innerText(),/Aberta/);
  assert.deepEqual(errors,[]);
  console.log('Browser OK: flow, same ISBN, correction, payment confirmation, real offline reload, search and mobile font enlargement.');
} finally {
  await browser?.close();await new Promise(resolve=>server.close(resolve));await rm(dir,{recursive:true,force:true});
}
